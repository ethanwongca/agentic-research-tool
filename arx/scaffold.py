"""Generate the stage boilerplate from the approved spec, so nobody hand-writes it."""
from __future__ import annotations

import re
import textwrap

from .spec import Project


def _bullets(items, indent="    ") -> str:
    return "\n".join(f"{indent}- {x}" for x in items) or f"{indent}(none)"


def render_stage(project: Project, sid: str) -> str:
    s = project.stage(sid)
    ins = s.get("inputs") or []
    outs = s.get("outputs") or []
    decs = [d for d in project.decisions(sid)]
    approach = textwrap.indent(textwrap.fill(str(s.get("approach", "")), 88), "    ")
    doc = f'''"""Stage `{sid}`: {s.get("title", sid)}

GENERATED BY arx FROM pipeline.yaml. The researcher's spec is the source of truth:
implement exactly this, read every choice from `params`, never hardcode them.

Purpose:
    {s.get("purpose", "")}

Approach (researcher-specified):
{approach}

Decisions (available as params[key]):
{_bullets([f"{d.get('key') or '(prose)'}: {d.get('question')} -> {d.get('answer')!r}" for d in decs])}

Constraints:
{_bullets(s.get("constraints") or [])}

Contract:
    inputs:  {", ".join(f"{i['name']} <- {i.get('from', '?')} ({i.get('type', '?')})" for i in ins) or "(none)"}
    outputs: {", ".join(f"{o['name']}: {o.get('type', '?')}" for o in outs)}

Verify with: arx verify {sid}
"""'''
    body = ["from __future__ import annotations", "", "from typing import Any", "", "",
            "def run(inputs: dict[str, Any], params: dict[str, Any], ctx: Any = None) -> dict[str, Any]:",
            '    """ctx.artifact_dir: write plots/reports here; they show up in `arx ui`."""']
    for i in ins:
        body.append(f'    {i["name"]} = inputs["{i["name"]}"]  # {i.get("type", "")} from {i.get("from", "")}')
    for d in decs:
        if not d.get("key"):
            continue
        ans = d.get("answer")
        if isinstance(ans, str) and re.search(r"\s", ans.strip()):
            body.append(f'    # {d["key"]}: {ans}')  # prose decision: implement it, don't parse it
        else:
            body.append(f'    {d["key"]} = params["{d["key"]}"]  # {ans!r}')
    for k in (s.get("params") or {}):
        body.append(f'    {k} = params["{k}"]')
    body.append("")
    body.append(f'    raise NotImplementedError("implement stage `{sid}` per the approach above")')
    body.append("")
    body.append("    return {")
    for o in outs:
        body.append(f'        "{o["name"]}": ...,  # {o.get("type", "")}  {o.get("description", "")}'.rstrip())
    body.append("    }")
    return doc + "\n" + "\n".join(body) + "\n"


def scaffold(project: Project, sid: str, force: bool = False) -> list[str]:
    created = []
    path = project.module_path(sid)
    if path.exists() and not force:
        return created
    path.parent.mkdir(parents=True, exist_ok=True)
    init = path.parent / "__init__.py"
    if not init.exists():
        init.write_text("")
    path.write_text(render_stage(project, sid))
    created.append(str(path.relative_to(project.root)))
    return created
